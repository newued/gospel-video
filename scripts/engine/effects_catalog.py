# ---------------------------------------------------------------------------
# 4. 标记解析：[[特效:名@时间|时长]]  ->  (name_raw, time_str, duration_str)
#    时间支持 "0:03" / "3s" / "3000ms"；时长支持 "2s" / "2000ms"。
#    例：[[特效:烟花]]  [[特效:震动@0:03|2s]]  [[特效:灵魂出窍@1.5s]]
# ---------------------------------------------------------------------------
_RE_EFFECT_TAG = re.compile(r"\[\[特效[:：]\s*([^\[\]|@]+?)\s*(?:@\s*([^\[\]|]+?))?\s*(?:\|\s*([^\[\]]+?))?\s*\]\]")


def parse_effect_tags(text: str) -> tuple[str, list[dict]]:
    """从一条消息文本中提取特效标记。

    Returns:
        (clean_text, effects)
        clean_text: 去掉所有 [[特效:...]] 标记后的纯对话文本
        effects: [{"name": 原始词, "at": 时间字符串或None, "dur": 时长字符串或None}, ...]
    """
    effects: list[dict] = []
    if not text:
        return text, effects

    def _repl(m):
        name = m.group(1).strip()
        at = (m.group(2) or "").strip() or None
        dur = (m.group(3) or "").strip() or None
        if name:
            effects.append({"name": name, "at": at, "dur": dur})
        return ""  # 标记本身从文本中移除

    clean = _RE_EFFECT_TAG.sub(_repl, text)
    clean = re.sub(r"\s{2,}", " ", clean).strip()
    return clean, effects


def normalize_effect(name: str) -> str:
    """把口语/变体特效词归一化为剪映真实 identifier。

    - 命中精确归一化表 -> 返回映射值
    - 否则原样透传（交给 jianying-editor 的 _resolve_enum 本地枚举匹配，
      仍可在 video_scene_effects.csv 命中；若剪映无此名则 QA 会报 missing）
    """
    if not name:
        return name
    return EFFECT_NORMALIZE.get(name, name)


def default_duration_for(name_norm: str) -> float:
    """查推荐默认时长，兜底 DEFAULT_DURATION。"""
    return float(EFFECT_DEFAULT_DURATION.get(name_norm, DEFAULT_DURATION))


def category_of(name_norm: str) -> str:
    """返回特效分类（基础画面特效 / 综艺特效 / 未知）。"""
    return _IDENT_TO_CAT.get(name_norm, "未知")


# ---------------------------------------------------------------------------
# 5. 便捷：把用户清单整体归一化一遍（用于文档自检 / 调试）
# ---------------------------------------------------------------------------
def demo_normalize(user_terms: list[str]) -> list[tuple[str, str]]:
    return [(t, normalize_effect(t)) for t in user_terms]


